export function getFiringIntervals(engine: EnginePreset): number[] {
  const ordered = [...engine.fire].sort((a, b) => a - b);
  return ordered.map((angle, index) =>
    index + 1 < ordered.length
      ? ordered[index + 1]! - angle
      : 720 - angle + ordered[0]!,
  );
}

