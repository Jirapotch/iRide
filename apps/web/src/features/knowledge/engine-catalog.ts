/** Mechanical and acoustic presets ported from the user-supplied Engine Simulator 3D. */
export interface EngineSound {
  pipe: number;
  open: number;
  damp: number;
  bright: number;
  mech: number;
  evo: number;
  punch: number;
}

export interface EnginePreset {
  id: string;
  cat: string;
  base: { inertia: number };
  n: number;
  lay: "I" | "V" | "B";
  va: number;
  name: string;
  crank: string;
  fire: number[];
  bank: number[];
  idle: number;
  red: number;
  tq: number;
  peak: number;
  snd: EngineSound;
  runner: number[] | null;
  turbo?: number;
  sc?: number;
  bg?: number;
}

type EngineInput = Omit<EnginePreset, "snd" | "runner"> & {
  snd?: Partial<EngineSound>;
  runner?: number[];
};

