export function engineDisplayName(
  engine: EnginePreset,
  locale: "th" | "en",
): string {
  if (locale === "th") return engine.name;
  return engine.name
    .replace(/^(\d+) สูบเรียง/, "$1-cylinder inline")
    .replace(/^(\d+) สูบ V/, "$1-cylinder V")
    .replace(/^(\d+) สูบ Boxer/, "$1-cylinder Boxer")
    .replace(/^1 สูบ/, "Single-cylinder")
    .replace(/ทัวริ่ง/g, "touring")
    .replace(/ไร้อัดอากาศ/g, "naturally aspirated")
    .replace(/ดีเซลเทอร์โบ/g, "turbo diesel")
    .replace(/ทวินเทอร์โบ/g, "twin-turbo")
    .replace(/เทอร์โบ/g, "turbo")
    .replace(/ซูเปอร์ชาร์จ/g, "supercharged")
    .replace(/เฮดเดอร์ไม่เท่า/g, "unequal headers");
}
